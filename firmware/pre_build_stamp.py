"""PlatformIO pre-build script: generate include/build_stamp.h with the real
build-host time. main.cpp's __DATE__/__TIME__ come from the .o compile time,
so incremental builds reuse a STALE stamp (observed: a main.cpp untouched
for hours flashed a clock seed 1.5 h behind). A generated header changes on
every build, forcing main.cpp to recompile with a fresh stamp.
Build host runs Pacific time, same TZ the board uses for seeding."""

Import("env")
import os, time

project_dir = env.subst("$PROJECT_DIR")
header = os.path.join(project_dir, "include", "build_stamp.h")

with open(header, "w") as f:
    f.write('/* generated by pre_build_stamp.py - do not commit or edit */\n')
    f.write('#define BUILD_STAMP_DATE "%s"\n' % time.strftime("%b %d %Y"))
    f.write('#define BUILD_STAMP_TIME "%s"\n' % time.strftime("%H:%M:%S"))
