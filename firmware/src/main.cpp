/* ------------------------------------------------------------------ */
/* wall clock: TZ + build-time seed + serial "TIME" sync command       */
/* ------------------------------------------------------------------ */
/* No battery-backed RTC and (currently) no NTP, so:
 *   1. system time is seeded from the build timestamp on every boot
 *      (accurate to ~a minute after flash / power cycle)
 *   2. the serial port accepts "TIME hh:mm:ss" or
 *      "TIME yyyy-mm-dd hh:mm:ss" to set exact local time
 * The header clock reads localtime() with TZ=PST8PDT (DST aware;
 * UTC-8 in winter, UTC-7 in summer). Drift: soft RTC keeps running
 * while powered (resets survive); hard power cycle = build seed.
 */
static const char *TZ_PACIFIC = "PST8PDT,M3.2.0,M11.1.0";

static void apply_time(struct tm *tmbuf, const char *src)
{
    time_t t = mktime(tmbuf);
    struct timeval tv = { t, 0 };
    settimeofday(&tv, nullptr);
    char buf[32];
    strftime(buf, sizeof(buf), "%Y-%m-%d %H:%M:%S %Z", localtime_r(&t, tmbuf));
    Serial.printf("[time] set from %s: %s\n", src, buf);
}

static void seed_time_from_build(void)
{
    /* BUILD_STAMP_* come from include/build_stamp.h, generated by
     * pre_build_stamp.py with the build-host time (Pacific). __DATE__/
     * __TIME__ were NOT usable: they carry the .o compile time, so
     * incremental builds re-flashed a stale stamp (observed 1.5 h off).
     * Parsing lives in wall_clock.{h,cpp} (host-tested); the never-
     * reachable unknown-month variant of a bad stamp now coalesces into
     * the parse-failed line below. */
    struct tm tmbuf;
    if (!wc_parse_build_stamp(BUILD_STAMP_DATE, BUILD_STAMP_TIME, &tmbuf)) {
        Serial.println("[time] build stamp parse failed");
        return;
    }

    /* Seed ONLY if the running RTC is behind the build stamp. Reboots (soft
     * reset) keep the RTC ticking, so re-seeding unconditionally would
     * rewind the clock to build time on every reboot — days off by the time
     * anyone notices. With the relay path the epoch field corrected this
     * within seconds; in direct mode the RTC is all we have. */
    time_t build_epoch = wc_tm_to_epoch(&tmbuf);
    if (wc_should_seed(time(nullptr), build_epoch)) {
        char stamp[80];
        snprintf(stamp, sizeof(stamp), "%s %s", BUILD_STAMP_DATE, BUILD_STAMP_TIME);
        apply_time(&tmbuf, stamp);
    } else {
        Serial.println("[time] RTC ahead of build stamp - kept");
    }
}

/* ------------------------------------------------------------------ */
/* SNAPSHOT / LVSNAP: binary frame dumps for host-side glitch watching  */
/* ------------------------------------------------------------------ */
/* Wire format (one frame):
 *   line:  "###SNAP <tag> <w> <h> <len> <fnv1a-hex>
"
 *   raw:   12-byte header ('S','N','A','P', int32 LE w, int32 LE h)
 *          (that header shape is what hostsim/raw2png.py reads)
 *          followed by <len> bytes of RGB565 pixels
 *   line:  "###SNAPEND
"
 * SNAPSHOT  = dumps BOTH RGB panel framebuffers (B0/B1: the pixels the
 *             panel DMA is actually fed under double buffering)
 * LVSNAP    = LVGL's own render of the active screen (what the firmware
 *             *thinks* is on screen). Together they triage panel-only
 *             vs write-path vs draw-state corruption. See docs/NOTES.md. */
static uint32_t fnv1a(const uint8_t *p, size_t n)
{
    uint32_t h = 2166136261u;
    while (n--) {
        h ^= *p++;
        h *= 16777619u;
    }
    return h;
}

/* Base64: the CH343/CDC link is NOT binary-safe (raw dumps lose 0x13 bytes
 * as flow-control artifacts). Everything after the marker line is base64;
 * the 12-byte raw2png header is rebuilt host-side from the marker line.*/
static const char kB64[] =
    "ABCDEFGHIJKLMNOPQRSTUVWXYZabcdefghijklmnopqrstuvwxyz0123456789+/";

static void emit_frame(const char *tag, int w, int h, const void *pix)
{
    size_t len = (size_t)w * h * sizeof(uint16_t);   /* RGB565 */
    const uint8_t *p = (const uint8_t *)pix;
    uint32_t fnv = fnv1a(p, len);
    Serial.printf("\n###SNAP %s %d %d %lu %08lx\n", tag, w, h,
                  (unsigned long)len, (unsigned long)fnv);
    Serial.flush();
    char out[5120 + 1];                              /* 3840 bytes -> 5120 b64 */
    while (len) {
        size_t n = (len < 3840) ? len : 3840;
        n -= n % 3;                                  /* keep 3-byte groups */
        char *o = out;
        for (size_t i = 0; i < n; i += 3) {
            uint32_t v = ((uint32_t)p[0] << 16) | ((uint32_t)p[1] << 8) | p[2];
            *o++ = kB64[(v >> 18) & 63];
            *o++ = kB64[(v >> 12) & 63];
            *o++ = kB64[(v >> 6) & 63];
            *o++ = kB64[v & 63];
            p += 3;
        }
        *o = 0;
        Serial.write((const uint8_t *)out, (size_t)(o - out));
        Serial.write('\n');
        len -= n;
    }
    /* len is now a multiple of 3 by construction (w*h*2 % 3 == 0 for 800x480: 768000 % 3 == 0) */
    Serial.print("###SNAPEND\n");
    Serial.flush();
}

static void *s_lv_snap_buf = nullptr;   /* PSRAM, LVGL view of the screen */

static void handle_snapshot(void)
{
    void *fb1 = nullptr, *fb2 = nullptr;
    int w = 0, h = 0;
    if (esp_lv_adapter_get_panel_framebuffers(&fb1, &fb2, &w, &h) != ESP_OK) {
        Serial.println("###SNAP err: framebuffers not ready");
        return;
    }
    /* Hold the LVGL lock so neither buffer is being written while we read;
     * the panel keeps DMA-scanning whatever buffer it has (static content).
     * ~16 s of dump pauses rendering and data-layer ticks - harmless. */
    ESP_ERROR_CHECK(esp_lv_adapter_lock(-1));
    emit_frame("B0", w, h, fb1);
    emit_frame("B1", w, h, fb2);
    esp_lv_adapter_unlock();
}

static void handle_lvsnap(void)
{
    int w = 0, h = 0;
    void *fb1 = nullptr, *fb2 = nullptr;
    if (esp_lv_adapter_get_panel_framebuffers(&fb1, &fb2, &w, &h) != ESP_OK) {
        Serial.println("###SNAP err: framebuffers not ready");
        return;
    }
    size_t need = (size_t)w * h * sizeof(uint16_t);
    if (s_lv_snap_buf == nullptr) {
        s_lv_snap_buf = heap_caps_malloc(need, MALLOC_CAP_SPIRAM);
        if (s_lv_snap_buf == nullptr) {
            Serial.println("###SNAP err: no PSRAM for lv snapshot");
            return;
        }
    }
    ESP_ERROR_CHECK(esp_lv_adapter_lock(-1));
    lv_img_dsc_t dsc;
    memset(&dsc, 0, sizeof(dsc));
    lv_res_t ok = lv_snapshot_take_to_buf(lv_scr_act(), LV_IMG_CF_TRUE_COLOR,
                                          &dsc, s_lv_snap_buf, (uint32_t)need);
    esp_lv_adapter_unlock();
    if (ok != LV_RES_OK) {
        Serial.println("###SNAP err: lv snapshot failed");
        return;
    }
    emit_frame("LV", dsc.header.w, dsc.header.h, dsc.data);
}

static void handle_serial_line(const String &line)
{
    String s = line;
    s.trim();
    if (s == "TIME ?") {
        time_t now = time(nullptr);
        struct tm tmbuf;
        localtime_r(&now, &tmbuf);
        char buf[40];
        strftime(buf, sizeof(buf), "%Y-%m-%d %H:%M:%S %Z (%z)", &tmbuf);
        Serial.printf("[time] now: %s\n", buf);
        return;
    }
    if (s.startsWith("TIME ")) {
        struct tm tmbuf;
        time_t now = time(nullptr);
        if (wc_parse_time_spec(s.c_str() + 5, now, localtime_r, &tmbuf)) {
            apply_time(&tmbuf, "serial");
        } else {
            Serial.println("[time] syntax: TIME hh:mm:ss | TIME yyyy-mm-dd hh:mm:ss | TIME ?");
        }
    }
    if (s == "FETCH") {
        dashboard_data_fetch_now();
    }
    if (s == "SNAPSHOT") {
        handle_snapshot();
    }
    if (s == "LVSNAP") {
        handle_lvsnap();
    }
    if (s.startsWith("PROBE ")) {
        dashboard_data_probe(s.c_str() + 6);
    }
}

void setup()
{
    /* 4 KB TX ring + 921600 baud: Serial.print() never spin-waits on the
     128-byte HW FIFO (see NOTES.md serial hardening rationale) */
    Serial.setTxBufferSize(4096);
    Serial.begin(921600);
    Serial.println("solar dashboard start");

    /* TZ must be set before any localtime()/mktime() use */
    setenv("TZ", TZ_PACIFIC, 1);
    tzset();
    seed_time_from_build();

    Board *board = new Board();
    Serial.printf("[s1] board created\n");
    if ((board == nullptr) || !board->init()) {
        Serial.println("Board init failed");
        while (true) {
            delay(1000);
        }
    }
    Serial.printf("[s2] board init done\n");

    const esp_lv_adapter_rotation_t rotation = ESP_LV_ADAPTER_ROTATE_0;
    const esp_lv_adapter_tear_avoid_mode_t tear_mode = ESP_LV_ADAPTER_TEAR_AVOID_MODE_DEFAULT_RGB;
    const uint8_t frame_buffer_count = esp_lv_adapter_get_required_frame_buffer_count(tear_mode, rotation);

    LCD *lcd = board->getLCD();
    if (lcd == nullptr) {
        Serial.println("LCD device is not available");
        while (true) {
            delay(1000);
        }
    }
    auto *lcd_bus = lcd->getBus();
    if (lcd_bus->getBasicAttributes().type == ESP_PANEL_BUS_TYPE_RGB) {
        lcd->configFrameBufferNumber(frame_buffer_count);
        static_cast<BusRGB *>(lcd_bus)->configRGB_BounceBufferSize(lcd->getFrameWidth() * 10);
    }

    assert(board->begin());
    Serial.printf("[s3] board begin done (LCD+bus configured)\n");

    esp_lv_adapter_config_t adapter_config = ESP_LV_ADAPTER_DEFAULT_CONFIG();
    adapter_config.task_stack_size = 12 * 1024;
    adapter_config.task_priority = 2;
    adapter_config.task_core_id = ARDUINO_RUNNING_CORE;
    ESP_ERROR_CHECK(esp_lv_adapter_init(&adapter_config));

    esp_lv_adapter_display_config_t disp_config = ESP_LV_ADAPTER_DISPLAY_RGB_DEFAULT_CONFIG(
        lcd, lcd->getFrameWidth(), lcd->getFrameHeight(), rotation
    );
    disp_config.profile.use_psram = true;

    lv_display_t *disp = esp_lv_adapter_register_display(&disp_config);
    assert(disp != nullptr);

    if (board->getTouch() != nullptr) {
        esp_lv_adapter_touch_config_t touch_config = ESP_LV_ADAPTER_TOUCH_DEFAULT_CONFIG(disp, board->getTouch());
        lv_indev_t *touch = esp_lv_adapter_register_touch(&touch_config);
        assert(touch != nullptr);
    }

    ESP_ERROR_CHECK(esp_lv_adapter_start());
    Serial.printf("[s4] adapter started\n");

#ifndef DBG1_NO_WIFI
    dashboard_data_init();
#else
    Serial.println("[dbg1] data layer disabled (glitch experiment)\n");
#endif

    ESP_ERROR_CHECK(esp_lv_adapter_lock(-1));
    dashboard_ui_init();
    esp_lv_adapter_unlock();

    Serial.println("solar dashboard ready");
    Serial.flush();
}

void loop()
{
    static uint32_t n = 0;
    static String cmdbuf;
    /* LVGL runs in the adapter's own task; don't touch it from here */
#ifndef DBG1_NO_WIFI
    dashboard_data_tick();
#endif
    while (Serial.available()) {
        char c = (char)Serial.read();
        if (c == '\r') {
            continue;
        }
        if (c == '\n') {
            if (cmdbuf.length()) {
                handle_serial_line(cmdbuf);
                cmdbuf = "";
            }
        } else if (cmdbuf.length() < 64) {
            cmdbuf += c;
        }
    }
    if ((++n % 50) == 0) {
        Serial.printf("[hb] alive t=%lu ms\n", (unsigned long)millis());
        Serial.flush();
    }
    delay(100);
}
